// Builds the Phosphor Light icon set used by the servizi icon picker:
//   inc/phosphor-light.php       name => inner SVG markup, for the front end
//                                (a plain PHP array, so opcache keeps it cheap)
//   assets/js/phosphor-light.js  [name, tags, inner SVG] list, for the
//                                wp-admin picker's grid and search
// Run with `npm run build:icons` after updating @phosphor-icons/core.

import { icons } from '@phosphor-icons/core';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// the package doesn't export its assets folder, so read it from node_modules
const assets = join('node_modules', '@phosphor-icons', 'core', 'assets', 'light');

const list = [];
for (const icon of icons) {
    const svg = readFileSync(join(assets, `${icon.name}-light.svg`), 'utf8');
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    const tags = icon.tags.filter((t) => !t.startsWith('*')).join(' ');
    list.push([icon.name, tags, inner]);
}

const php = "<?php\n// generated by scripts/build-phosphor.mjs — do not edit\nreturn [\n"
    + list.map(([n, , s]) => `    '${n}' => '${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`).join('\n')
    + "\n];\n";
writeFileSync('inc/phosphor-light.php', php);

writeFileSync('assets/js/phosphor-light.js',
    '// generated by scripts/build-phosphor.mjs — do not edit\nwindow.SP_PHOSPHOR_LIGHT = ' + JSON.stringify(list) + ';\n');

console.log(`${list.length} icons`);
